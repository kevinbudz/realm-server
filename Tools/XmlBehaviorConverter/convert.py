class Data:
    pass


def gather():
    d = Data()
    d.server_ids = {}
    d.items = {}
    for p in glob.glob(os.path.join(GAMEDATA, '*.xml')):
        try:
            root = load_xml(p)
        except ET.ParseError:
            continue
        for o in root.iter('Object'):
            oid = o.get('id')
            if not oid:
                continue
            d.server_ids[oid] = int(o.get('type'), 16) if o.get('type') else -1
            if o.find('Item') is not None:
                d.items[oid.lower()] = oid

    d.stringlists = {}
    sl = os.path.join(SRC_XML, 'stringlist.xml')
    if os.path.exists(sl):
        for lst in load_xml(sl).iter('StringList'):
            d.stringlists[lst.get('id')] = {
                s.get('id'): [x.text.strip() for x in s.findall('String') if x.text and x.text.strip()]
                for s in lst.findall('Strings')}

    d.sources = []   # (relpath, [Object elements])
    for p in sorted(glob.glob(os.path.join(SRC_XML, '**', '*.xml'), recursive=True)):
        rel = os.path.relpath(p, SRC_XML)
        try:
            root = load_xml(p)
        except ET.ParseError as e:
            REPORT.add('unparsable source files', f'{rel}: {e}')
            continue
        objs = [o for o in root.iter('Object')
                if any(c.tag in ('Behavior', 'State', 'SoulboundLoot', 'Loot') for c in o.iter())]
        if objs:
            d.sources.append((rel, objs))
    return d


def is_generated(path):
    with open(path, encoding='utf-8-sig', errors='replace') as f:
        first = f.readline().rstrip('\r\n')
    return MARKER_RE.match(first) is not None


def legacy_files():
    """Files of the previous Extracted/ output, or [] if the dir is absent.
    Exits if the directory holds anything this script did not write."""
    if not os.path.isdir(LEGACY_DIR):
        return []
    paths = []
    for name in sorted(os.listdir(LEGACY_DIR)):
        p = os.path.join(LEGACY_DIR, name)
        with open(p, encoding='utf-8-sig', errors='replace') as f:
            line1, line2 = f.readline().rstrip('\r\n'), f.readline().rstrip('\r\n')
        if not (name.endswith('.cs') and line1 == '// <auto-generated>'
                and line2.startswith(LEGACY_LINE2)):
            sys.exit(f'error: {p} is not a generated file; not removing {LEGACY_DIR}')
        paths.append(p)
    return paths


# --------------------------------------------------------------------------
# Preprocessing: <DefineEmbed>/<Embed> macro expansion and id renames
# --------------------------------------------------------------------------
def _subst(text, params):
    if not text or '{' not in text:
        return text
    return re.sub(r'\{([A-Za-z_][A-Za-z0-9_]*)\}',
                  lambda m: params.get(m.group(1), m.group(0)), text)


def _expand_children(parent, defs, params, oid, depth=0):
    """Rebuilds parent's children with every <Embed> replaced by a copy of its
    <DefineEmbed> body ({name} placeholders substituted from <Param>s)."""
    if depth > 20:
        REPORT.add('embed errors', f'{oid}: embed recursion too deep')
        return
    new_children = []
    for ch in list(parent):
        if ch.tag == 'DefineEmbed':
            continue
        if ch.tag == 'Embed':
            name = ch.get('name')
            body = defs.get(name)
            if body is None:
                REPORT.add('embed errors', f'{oid}: undefined embed "{name}"')
                continue
            local = dict(params)
            for prm in ch.findall('Param'):
                local[prm.get('name')] = _subst((prm.text or '').strip(), params)
            holder = ET.Element('holder')
            for b in body:
                holder.append(copy.deepcopy(b))
            _apply_params(holder, local)
            _expand_children(holder, defs, local, oid, depth + 1)
            new_children.extend(list(holder))
            continue
        _expand_children(ch, defs, params, oid, depth)
        new_children.append(ch)
    for ch in list(parent):
        parent.remove(ch)
    parent.extend(new_children)


def _apply_params(el, params):
    for e in el.iter():
        for k, v in list(e.attrib.items()):
            e.set(k, _subst(v, params))
        if e.tag != 'Param':
            e.text = _subst(e.text, params)


def _rename(el, rename):
    if not rename:
        return
    for e in el.iter():
        for k, v in list(e.attrib.items()):
            parts = [x.strip() for x in v.split(',')]
            if any(x in rename for x in parts):
                e.set(k, ','.join(rename.get(x, x) for x in parts))
        if e.tag in ('Transition',):
            continue


def preprocess(obj, rename):
    obj = copy.deepcopy(obj)
    defs = {d.get('name'): d for d in obj.iter('DefineEmbed')}
    if obj.find('.//Embed') is not None:
        _expand_children(obj, defs, {}, obj.get('id'))
    else:
        for d in list(obj.iter('DefineEmbed')):
            pass
        for d in obj.findall('DefineEmbed'):
            obj.remove(d)
    _rename(obj, rename)
    if obj.get('id') in rename:
        obj.set('id', rename[obj.get('id')])
    return obj


HEADER = '''// <auto-generated> by Tools/XmlBehaviorConverter/convert.py from files/xml/{src}. Do not edit; regenerate.
// </auto-generated>
using RotMG.Common;
using RotMG.Game.Logic.Behaviors;
using RotMG.Game.Logic.Loots;
using RotMG.Game.Logic.Transitions;

namespace RotMG.Game.Logic.Database
{{
    public class {cls} : IBehaviorDatabase
    {{
        public void Init(BehaviorDb db)
        {{
{body}
        }}
    }}
}}
'''


def main():
    report_path = None
    if '--report' in sys.argv:
        report_path = sys.argv[sys.argv.index('--report') + 1]
    d = gather()

    # Server objects renamed relative to files/xml (same type code, different
    # id) are bridge copies: keep the server's id so Resources resolve.
    type2server = {t: i for i, t in d.server_ids.items() if t >= 0}
    rename = {}
    defined = {o.get('id') for _, objs in d.sources for o in objs}
    for rel, objs in d.sources:
        for o in objs:
            oid = o.get('id')
            if oid in d.server_ids or not o.get('type'):
                continue
            t = int(o.get('type'), 16)
            if t in type2server and type2server[t] not in defined:
                rename[oid] = type2server[t]
                REPORT.add('renamed (files id -> server id, same type)', f'{oid} -> {type2server[t]}')

    # Everything is rendered in memory first, so a failure leaves the tree untouched.
    if len(set(NAMES.values())) != len(NAMES):
        sys.exit('error: duplicate database name in NAMES')
    outputs = []        # (name, src, text, object count)
    unmapped = []
    emitted_ids = set()
    total = 0
    for rel, objs in d.sources:
        blocks = []
        for raw in objs:
            o = preprocess(raw, rename)
            oid = o.get('id')
            if oid in emitted_ids:
                REPORT.add('duplicates', f'{rel}: {oid} already emitted from another file')
                continue
            if oid not in d.server_ids:
                REPORT.add('not in server data (skipped)', f'{rel}: {oid}')
                continue
            if (o.findtext('Class') or '').strip() in SKIP_CLASSES:
                REPORT.add('engine-managed class (skipped)', f'{rel}: {oid} ({o.findtext("Class")})')
                continue
            code = emit_object(o, Ctx(oid, d))
            if code:
                blocks.append(f'            // {oid}\n' + code)
                emitted_ids.add(oid)
        if not blocks:
            continue
        src = rel.replace(os.sep, '/')
        name = NAMES.get(src)
        if name is None:
            unmapped.append(src)
            continue
        outputs.append((name, src, HEADER.format(src=src, cls=name, body='\n\n'.join(blocks)), len(blocks)))
        total += len(blocks)
    if unmapped:
        sys.exit('error: no NAMES entry for files/xml sources that emit behaviors: ' + ', '.join(unmapped))

    # Refuse before deleting anything if a target is a file this script did not write.
    for name, _, _, _ in outputs:
        path = os.path.join(DB_DIR, name + '.cs')
        if os.path.exists(path) and not is_generated(path):
            sys.exit(f'error: {path} exists without the generated marker; not overwriting it')
    stale = [p for p in glob.glob(os.path.join(DB_DIR, '*.cs')) if is_generated(p)]
    legacy = legacy_files()

    for p in stale + legacy:
        os.remove(p)
    if os.path.isdir(LEGACY_DIR):
        os.rmdir(LEGACY_DIR)
    for name, src, text, n in outputs:
        with open(os.path.join(DB_DIR, name + '.cs'), 'w', encoding='utf-8') as f:
            f.write(text)
        print(f'{name}: {n} objects ({src})')
    print(f'total objects emitted: {total}')
    if report_path:
        with open(report_path, 'w', encoding='utf-8') as f:
            f.write(f'Emitted objects: {total}\n\n')
            for sec in sorted(REPORT.lines):
                f.write(f'== {sec} ({len(set(REPORT.lines[sec]))})\n')
                for line in sorted(set(REPORT.lines[sec])):
                    f.write(f'  {line}\n')
                f.write('\n')


if __name__ == '__main__':
    main()
