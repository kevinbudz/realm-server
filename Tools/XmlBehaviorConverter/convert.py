# Transition mapping
# --------------------------------------------------------------------------
def map_condition(key, value, target, ctx):
    t = cs_str(target)
    if key == 'aftertime':
        return f'new TimedTransition({ms(float(value))}, {t})'
    if key == 'hitpointslessthan':
        return f'new HpLessTransition({cs_num(float(value))}, {t})'
    if key == 'random':
        return f'new RandomTransition({cs_num(float(value))}, {t})'
    if key == 'playerwithin':
        parts = value.split('|')
        if len(parts) > 1:
            return f'new PlayerWithinTransition({cs_num(float(parts[0]))}, {t}, minPlayers: {int(float(parts[1]))})'
        return f'new PlayerWithinTransition({cs_num(float(parts[0]))}, {t})'
    if key == 'noplayerwithin':
        return f'new PlayerWithinTransition({cs_num(float(value))}, {t}, invert: true)'
    if key == 'exist':
        return f'new WorldEntitiesTransition({cs_str(value)}, true, {t})'
    if key == 'noneexist':
        return f'new WorldEntitiesTransition({cs_str(value)}, false, {t})'
    if key == 'hastag':
        return f'new TagTransition({cs_str(value)}, true, {t})'
    if key == 'notag':
        return f'new TagTransition({cs_str(value)}, false, {t})'
    if key == 'hasglobaltag':
        return f'new GlobalTagTransition({cs_str(value)}, true, {t})'
    if key == 'noglobaltag':
        return f'new GlobalTagTransition({cs_str(value)}, false, {t})'
    if key == 'playersays':
        return f'new PlayerSaysTransition({cs_str(value)}, {t})'
    if key == 'ontile':
        return f'new OnTileTransition({cs_str(value)}, {t})'
    REPORT.add('skipped transitions', f'{ctx.obj_id}: unknown condition "{key}"')
    return None


def map_transition(el, ctx):
    targets = [s.strip() for s in (el.text or '').split(',') if s.strip()]
    if not targets:
        REPORT.add('skipped transitions', f'{ctx.obj_id}: transition without target')
        return None
    conds = list(norm_attrs(el).items())
    if not conds:
        # Old engine: a condition-less transition passes immediately.
        return 'new AllTransition({})'.format(cs_str(','.join(targets)))
    if len(conds) == 1 and len(targets) == 1:
        return map_condition(conds[0][0], conds[0][1], targets[0], ctx)
    inner = [map_condition(k, v, '', ctx) for k, v in conds]
    if any(i is None for i in inner):
        return None
    return 'new AllTransition({}, {})'.format(cs_str(','.join(targets)), ', '.join(inner))


# --------------------------------------------------------------------------
# Structure
# --------------------------------------------------------------------------
def emit_behaviors(container, ctx):
    """Returns ordered list of C# expressions for the <Behavior> children of a
    container, grouping same-bucket behaviors into Prioritize like the old
    engine (the first behavior in a bucket that acts wins)."""
    items = []          # list of either str or ('bucket', name, [exprs])
    buckets = {}
    for el in container.findall('Behavior'):
        expr = map_behavior(el, ctx)
        if expr is None:
            continue
        exprs = expr if isinstance(expr, list) else [expr]
        bucket = el.get('bucket', '').strip()
        if bucket:
            if bucket not in buckets:
                buckets[bucket] = []
                items.append(('bucket', bucket, buckets[bucket]))
            buckets[bucket].extend(exprs)
        else:
            items.extend(exprs)
    out = []
    for it in items:
        if isinstance(it, tuple):
            exprs = it[2]
            out.append(exprs[0] if len(exprs) == 1 else ('new Prioritize(' + ', '.join(exprs) + ')', exprs))
        else:
            out.append(it)
    return out


def emit_orders(container, ctx, state_name):
    for od in container.findall('Order'):
        if od.findall('State') or od.findall('Transition'):
            REPORT.add('approximations', f'{ctx.obj_id}: nested states inside <Order> of state "{state_name}" flattened to behaviors')
        beh = emit_behaviors(od, ctx)
        for st in od.iter('State'):
            beh.extend(emit_behaviors(st, ctx))
        beh = [b if isinstance(b, str) else b[0] for b in beh]
        if not beh:
            continue
        ctx.orders.append((state_name, od.get('targetIds'), beh))


def fmt_list(exprs, indent):
    pad = ' ' * indent
    out = []
    for e in exprs:
        if isinstance(e, tuple):
            inner = (',\n' + pad + '    ').join(e[1])
            out.append(f'new Prioritize(\n{pad}    {inner}\n{pad})')
        else:
            out.append(e)
    return out


def emit_state(st, ctx, indent, path=''):
    pad = ' ' * indent
    sid = st.get('id', '')
    path = (path + '/' + sid) if path else sid
    emit_orders(st, ctx, path.lower())
    parts = fmt_list(emit_behaviors(st, ctx), indent + 4)
    for tr in st.findall('Transition'):
        t = map_transition(tr, ctx)
        if t:
            parts.append(t)
    for child in st.findall('State'):
        parts.append(emit_state(child, ctx, indent + 4, path))
    if not parts:
        return f'new State({cs_str(sid)})'
    body = (',\n' + pad + '    ').join(parts)
    return f'new State({cs_str(sid)},\n{pad}    {body}\n{pad})'


def map_loot(el, ctx):
    a = norm_attrs(el)
    name = (el.text or '').strip()
    prob = fnum(a, 'prob', 1.0)
    thr = a.get('threshold')
    thr_s = f', threshold: {cs_num(float(thr))}f' if thr else ''
    if 'tier' in a:
        tt = TIER_TYPES.get(name.replace(' ', '').lower())
        if not tt:
            REPORT.add('skipped loot', f'{ctx.obj_id}: unknown tier loot type "{name}"')
            return None
        return f'new TierLoot({inum(a, "tier", 1)}, TierLoot.LootType.{tt}, {cs_num(prob)}f{thr_s})'
    if name.lower() not in ctx.data.items:
        REPORT.add('skipped loot', f'{ctx.obj_id}: item "{name}" not in server data')
        return None
    real = ctx.data.items[name.lower()]
    return f'new ItemLoot({cs_str(real)}, {cs_num(prob)}f{thr_s})'


def emit_object(obj, ctx):
    ctx.orders = []
    oid = obj.get('id')
    parts = []
    emit_orders(obj, ctx, '')
    parts.extend(fmt_list(emit_behaviors(obj, ctx), 16))
    for tr in obj.findall('Transition'):
        t = map_transition(tr, ctx)
        if t:
            parts.append(t)
    for st in obj.findall('State'):
        parts.append(emit_state(st, ctx, 16))
    for lt in obj:
        if lt.tag in ('SoulboundLoot', 'Loot'):
            l = map_loot(lt, ctx)
            if l:
                parts.append(l)
    lines = []
    if parts:
        body = (',\n' + ' ' * 16).join(parts)
        lines.append(f'            db.Init({cs_str(oid)},\n                {body}\n            );')
    for state_name, targets, beh in ctx.orders:
        tg = cs_str(targets) if targets else 'null'
        body = (',\n' + ' ' * 16).join(beh)
        lines.append(f'            OrderDb.Register({cs_str(oid)}, {cs_str(state_name)}, {tg},\n                {body}\n            );')
    return '\n'.join(lines)


