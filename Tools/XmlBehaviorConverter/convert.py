# --------------------------------------------------------------------------
# XML loading
# --------------------------------------------------------------------------
def load_xml(path):
    text = open(path, encoding='utf-8', errors='replace').read()
    text = re.sub(r'&(?!amp;|lt;|gt;|quot;|apos;|#)', '&amp;', text)
    return ET.fromstring(text)


def norm_attrs(el):
    out = {}
    for k, v in el.attrib.items():
        k = k.lower()
        out[ATTR_ALIASES.get(k, k)] = v.strip()
    return out


class Report:
    def __init__(self):
        self.lines = collections.defaultdict(list)

    def add(self, section, msg):
        self.lines[section].append(msg)


REPORT = Report()


# --------------------------------------------------------------------------
# C# literal helpers
# --------------------------------------------------------------------------
def cs_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def cs_num(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    r = repr(float(v))
    if r.endswith('.0'):
        r = r[:-2]
    return r


def cs_f(v):
    """float literal (for float-typed parameters)."""
    return cs_num(v) + 'f' if not isinstance(v, int) or True else str(v)


def fnum(a, key, default):
    v = a.get(key)
    if v is None or v == '':
        return default
    try:
        return float(v)
    except ValueError:
        m = re.match(r'\s*(-?[0-9.]+)', v)
        return float(m.group(1)) if m else default


def inum(a, key, default):
    return int(round(fnum(a, key, default)))


def fbool(a, key, default):
    v = a.get(key)
    if v is None:
        return default
    return not (v == '0' or v.lower() == 'false')


def ms(seconds):
    # Legacy XML uses huge cooldowns (e.g. 100000000 s) to mean "once per
    # state entry"; clamp to the C# int range.
    return max(-2147483647, min(2147483647, int(round(seconds * 1000))))


def hexcolor(a, key, default):
    v = a.get(key)
    if v is None:
        return default
    v = v.strip().lower().replace('#', '')
    if v.startswith('0x'):
        v = v[2:]
    try:
        return int(v, 16)
    except ValueError:
        return default


def args(*pos, **named):
    parts = [p for p in pos if p is not None]
    for k, v in named.items():
        if v is None:
            continue
        parts.append(f'{k}: {v}')
    return ', '.join(parts)


def effect_enum(name, ctx):
    key = (name or '').replace(' ', '').lower()
    if key in CONDITION_EFFECTS:
        return 'ConditionEffectIndex.' + CONDITION_EFFECTS[key]
    REPORT.add('unknown condition effects', f'{ctx}: "{name}"')
    return None


# --------------------------------------------------------------------------
# Behavior mapping
# --------------------------------------------------------------------------
class Ctx:
    def __init__(self, obj_id, data):
        self.obj_id = obj_id
        self.data = data


def map_shoot(a, ctx):
    stype = a.get('type', 'targeted').lower()
    rng = fnum(a, 'range', 8.0)
    count = inum(a, 'numshots', 1)
    inc = fnum(a, 'angle', 9.0)
    cooldown = ms(fnum(a, 'cooldown', 1.0))
    offset = ms(fnum(a, 'offset', 0.0))
    predictive = fnum(a, 'predictive', 0.0)
    default_angle = fnum(a, 'defaultangle', 90.0)
    jitter = fbool(a, 'cooldownjitter', False)
    child = a.get('childid')
    if a.get('arcdegrees'):
        REPORT.add('approximations', f'{ctx.obj_id}: Shoot arcDegrees ignored (target picked from any direction)')
    if a.get('blasteffect'):
        REPORT.add('approximations', f'{ctx.obj_id}: Shoot blastEffect visual ignored')
    if child:
        # Old engine: spawn numShots copies of childId at the host instead of firing.
        if count != 1:
            REPORT.add('approximations', f'{ctx.obj_id}: Shoot childId "{child}" spawns 1 object per cooldown instead of {count}')
        return f'new MakeMinions({cs_str(child)}, maxChildren: 0, cooldown: {cooldown}, startWithMinions: false)'
    if stype == 'forward':
        # ShootForward (fires along the host's movement direction) was removed; no surviving Shoot does this.
        REPORT.add('skipped behaviors', f'{ctx.obj_id}: Shoot type="forward" not ported (fires along movement direction)')
        return None

    named = dict(index=a.get('projectileid', '0'))
    named['count'] = str(count)
    if count > 1:
        named['shootAngle'] = cs_num(inc) + 'f'
    if stype == 'auto':
        # Old: start = angle - inc * floor(n/2); C#: start = angle - inc * (n-1)/2.
        fixed = default_angle - inc * (count // 2) + inc * (count - 1) / 2.0
        fixed = round(fixed, 4)
        named['fixedAngle'] = cs_num(fixed) + 'f'
    if predictive:
        named['predictive'] = cs_num(predictive) + 'f'
    if offset:
        named['cooldownOffset'] = str(offset)
    if jitter:
        named['cooldownVariance'] = str(cooldown // 2)
    named['cooldown'] = str(cooldown)
    return f'new Shoot({cs_num(rng)}f, {", ".join(f"{k}: {v}" for k, v in named.items())})'


def map_behavior(el, ctx):
    name = (el.text or '').strip()
    a = norm_attrs(el)
    oid = ctx.obj_id
    if name == 'Shoot':
        return map_shoot(a, ctx)
    if name == 'Wander':
        return f'new Wander({cs_num(fnum(a, "speed", 0.4))}f)'
    if name == 'Charge':
        return f'new Charge({cs_num(fnum(a, "speed", 3.0))}, {cs_num(fnum(a, "range", 20.0))}f, cooldown: {ms(fnum(a, "cooldown", 3.0))})'
    if name == 'Follow':
        if fbool(a, 'predictive', False):
            REPORT.add('approximations', f'{oid}: Follow predictive ignored')
        return 'new Follow({}, acquireRange: {}, range: {}, duration: {}, cooldown: {})'.format(
            cs_num(fnum(a, 'speed', 1.0)), cs_num(fnum(a, 'acquirerange', 10.0)),
            cs_num(fnum(a, 'range', a and fnum(a, 'distance', 3.0))),
            ms(fnum(a, 'duration', 30.0)), ms(fnum(a, 'cooldown', 5.0)))
    if name == 'ChangeSize':
        rate = fnum(a, 'rate', 0.2)
        if rate == 0:
            return None
        target = fnum(a, 'maxsize', 200.0) if rate > 0 else fnum(a, 'minsize', 60.0)
        # Old: rate * 5 size units per second; C#: Rate units every 150 ms.
        step = int(round(rate * 0.75))
        if step == 0:
            step = 1 if rate > 0 else -1
        return f'new ChangeSize({step}, {int(round(target))})'
    if name == 'Metamorphose':
        return 'new Metamorphose({}, time: {}, dropLoot: {}, giveXP: {})'.format(
            cs_str(a.get('childid', oid)), ms(fnum(a, 'time', 60.0)),
            cs_num(fbool(a, 'droploot', False)), cs_num(fbool(a, 'givexp', False)))
    if name == 'MetamorphoseAtDeath':
        return 'new TransformOnDeath({}, 1, 1, {})'.format(cs_str(a.get('childid', '')), cs_num(fnum(a, 'prob', 1.0)))
    if name == 'ReleaseSpawnAtDeath':
        return 'new TransformOnDeath({}, {}, {})'.format(cs_str(a.get('childid', '')), inum(a, 'min', 2), inum(a, 'max', 7))
    if name == 'Explode':
        return 'new Explode(projectileIndex: {}, count: {}, range: {}, initialDelay: {}, arcDegrees: {}, dropLoot: {}, giveXP: {})'.format(
            inum(a, 'projectileid', 0), inum(a, 'numshots', 12), cs_num(fnum(a, 'range', 5.0)),
            ms(fnum(a, 'initialdelay', 0.0)), inum(a, 'arcdegrees', 360),
            cs_num(fbool(a, 'droploot', False)), cs_num(fbool(a, 'givexp', False)))
    if name == 'Protect':
        prot = fnum(a, 'protectionrange', 3.0)
        return 'new Protect({}, {}, acquireRange: {}, protectionRange: {}, reprotectRange: {})'.format(
            cs_num(fnum(a, 'speed', 0.8)), cs_str(a.get('protecteeid', '')),
            cs_num(fnum(a, 'acquirerange', 15.0)), cs_num(prot), cs_num(fnum(a, 'reprotectrange', prot)))
    if name == 'VictoryAtDeath':
        return 'new VictoryAtDeath()'
    if name == 'Taunt':
        lst = a.get('listid', oid)
        strings = ctx.data.stringlists.get(lst, {})
        texts = strings.get('everySoOften') or strings.get('new') or []
        if not texts:
            REPORT.add('skipped behaviors', f'{oid}: Taunt list "{lst}" has no usable strings')
            return None
        if any(';' in t for t in texts):
            REPORT.add('skipped behaviors', f'{oid}: Taunt list "{lst}" has a line with ";" (Say splits on ";")')
            return None
        return 'new Say({}, probability: 1, broadcast: {}, bubbleTime: 10, cooldown: 20000)'.format(
            cs_str(';'.join(texts)), cs_num(fbool(a, 'broadcast', False)))
    if name == 'Say':
        return 'new Say({}, probability: {}, broadcast: {}, bubbleTime: {})'.format(
            cs_str(a.get('text', '')), cs_num(fnum(a, 'prob', 1.0)),
            cs_num(fbool(a, 'broadcast', False)), inum(a, 'bubbletime', 10))
    if name == 'RemoveOnEmpty':
        REPORT.add('skipped behaviors', f'{oid}: RemoveOnEmpty not ported (containers are engine-managed)')
        return None
    if name == 'StayAbove':
        return 'new StayAbove({}, {})'.format(cs_num(fnum(a, 'speed', 0.5)), inum(a, 'minaltitude', 200))
    if name == 'StayInTerrain':
        return 'new StayInTerrain({}, speed: {})'.format(cs_str(a.get('terrain', '')), cs_num(fnum(a, 'speed', 0.5)))
    if name == 'MakeMinions':
        return 'new MakeMinions({}, maxChildren: {}, cooldown: {}, startWithMinions: {}, group: {}, minOffset: {}, maxOffset: {}, cooldownJitter: {})'.format(
            cs_str(a['childids']) if a.get('childids') else 'null', inum(a, 'maxchildren', 0),
            ms(fnum(a, 'cooldown', 30.0)), cs_num(fbool(a, 'startwithminions', True)),
            cs_str(a['groupid']) if a.get('groupid') else 'null',
            cs_num(fnum(a, 'minoffset', 0.0)), cs_num(fnum(a, 'maxoffset', 0.0)),
            cs_num(fbool(a, 'cooldownjitter', False)))
    if name == 'Decay':
        if a.get('particleeffect'):
            REPORT.add('approximations', f'{oid}: Decay particle effect ignored')
        if fbool(a, 'droploot', False) or fbool(a, 'givexp', False):
            REPORT.add('approximations', f'{oid}: Decay dropLoot/giveXP ignored (entity is removed)')
        return f'new Decay({ms(fnum(a, "time", 60.0))})'
    if name == 'OryxTaunt':
        return 'new OryxTaunt()'
    if name == 'Orbit':
        if a.get('radiuswobbledistance'):
            REPORT.add('approximations', f'{oid}: Orbit radius wobble ignored')
        speed = fnum(a, 'speed', 0.8)
        radius = fnum(a, 'radius', 5.0)
        # Reference treats the variabilities as fractions of speed and radius; Orbit takes absolute amounts.
        return 'new Orbit({}, {}, acquireRange: {}, target: {}, speedVariance: {}, radiusVariance: {}, orbitClockwise: {})'.format(
            cs_num(speed), cs_num(radius),
            cs_num(fnum(a, 'acquirerange', 15.0)),
            cs_str(a['protecteeid']) if a.get('protecteeid') else 'null',
            cs_num(round(speed * fnum(a, 'speedvariability', 0.2), 9)),
            cs_num(round(radius * fnum(a, 'radiusvariability', 0.5), 9)),
            cs_num(fbool(a, 'clockwise', False)))
    if name == 'Heal':
        return 'new Heal(range: {}, cooldown: {}, targetIds: {}, targetGroups: {}, maxTargets: {}, maxHeal: {}, hideVisual: {})'.format(
            cs_num(fnum(a, 'range', 10.0)), ms(fnum(a, 'cooldown', 10.0)),
            cs_str(a['targetids']) if a.get('targetids') else 'null',
            cs_str(a['targetgroups']) if a.get('targetgroups') else 'null',
            inum(a, 'maxtargets', -1), inum(a, 'maxheal', -1), cs_num(fbool(a, 'hidevisual', False)))
    if name == 'StayBack':
        dist = cs_num(fnum(a, 'distance', 10.0))
        return 'new KeepDistance({}, {}, {}, approach: false, deadband: 0)'.format(cs_num(fnum(a, 'speed', 1.0)), dist, dist)
    if name == 'KeepDistance':
        return 'new KeepDistance({}, {}, {})'.format(cs_num(fnum(a, 'speed', 1.0)), cs_num(fnum(a, 'distance', 10.0)), cs_num(fnum(a, 'acquirerange', 15.0)))
    if name == 'Circle':
        return 'new Orbit({}, {}, acquireRange: {}, speedVariance: 0, radiusVariance: 0, orbitClockwise: null, reportMoved: true)'.format(
            cs_num(fnum(a, 'speed', 1.0)), cs_num(fnum(a, 'distance', 8.0)), cs_num(fnum(a, 'acquirerange', 15.0)))
    if name == 'StayCloseToSpawn':
        if a.get('cooldown'):
            REPORT.add('approximations', f'{oid}: StayCloseToSpawn cooldown ignored')
        return 'new StayCloseToSpawn({}, {})'.format(cs_num(fnum(a, 'speed', 1.0)), inum(a, 'range', 7))
    if name == 'FollowOrders':
        return 'new FollowOrders({}, acquireRange: {}, cooldown: {})'.format(
            cs_str(a.get('listenids', '')), cs_num(fnum(a, 'acquirerange', 15.0)), ms(fnum(a, 'cooldown', 3.0)))
    if name == 'Swirl':
        return 'new Swirl({}, {})'.format(cs_num(fnum(a, 'speed', 2.0)), cs_num(fnum(a, 'distance', 8.0)))
    if name == 'Buzz':
        return 'new Buzz({})'.format(cs_num(fnum(a, 'speed', 15.0) / 10.0))
    if name == 'BackAndForth':
        return 'new BackAndForth({}, {})'.format(cs_num(fnum(a, 'speed', 1.0)), inum(a, 'radius', 4))
    if name == 'Move':
        return 'new MoveInDirection({}, {}, {}, {})'.format(
            cs_num(fnum(a, 'speed', 1.0)), cs_num(fnum(a, 'distance', 3.0)),
            cs_num(fnum(a, 'angle', 0.0)), ms(fnum(a, 'cooldown', 10.0)))
    if name == 'MaintainProtectors':
        return 'new MaintainProtectors({}, childCorpse: {}, numChildren: {}, cooldown: {}, distance: {})'.format(
            cs_str(a.get('childids', '')), cs_str(a['childcorpseid']) if a.get('childcorpseid') else 'null',
            inum(a, 'numchildren', 2), ms(fnum(a, 'cooldown', 30.0)), cs_num(fnum(a, 'distance', 0)))
    if name == 'RemainVisible':
        return 'new RemainVisible()'
    if name == 'Zap':
        eff = a.get('conditioneffect')
        return 'new Zap(radius: {}, damage: {}, cooldown: {}, color: 0x{:X}, conditionEffect: {}, conditionDuration: {}, poisonTotalDamage: {}, poisonDuration: {})'.format(
            cs_num(fnum(a, 'radius', fnum(a, 'range', 5.0))), inum(a, 'damage', 10), ms(fnum(a, 'cooldown', 1.0)),
            hexcolor(a, 'color', 0xFFFFFF), cs_str(eff) if eff else 'null',
            ms(fnum(a, 'conditionduration', 0.0)), inum(a, 'poisontotaldamage', 0), ms(fnum(a, 'poisonduration', 0.0)))
    if name == 'HealZap':
        return 'new HealZap(radius: {}, healing: {}, cooldown: {}, color: 0x{:X})'.format(
            cs_num(fnum(a, 'radius', fnum(a, 'range', 5.0))), inum(a, 'healing', 25),
            ms(fnum(a, 'cooldown', 1.0)), hexcolor(a, 'color', 0xFFFFFF))
    if name == 'TrapTrigger':
        return ('new TrapTrigger(radius: {}, radiusVariability: {}, minDamage: {}, maxDamage: {}, posJitter: {}, '
                'condEffect: {}, condDuration: {}, cooldown: {}, cooldownJitter: {}, soundId: {}, color: 0x{:X})').format(
            cs_num(fnum(a, 'radius', 1.0)), cs_num(fnum(a, 'radiusvariability', 0.0)),
            inum(a, 'mindamage', 10), inum(a, 'maxdamage', 10), cs_num(fnum(a, 'posjitter', 0.0)),
            cs_str(a['condeffect']) if a.get('condeffect') else 'null', ms(fnum(a, 'condduration', 5.0)),
            ms(fnum(a, 'cooldown', 3.0)), ms(fnum(a, 'cooldownjitter', 0.0)), inum(a, 'soundid', -1),
            hexcolor(a, 'color', 0xaa00ff))
    if name == 'Shadow':
        return 'new Shadow({}, {}, {})'.format(cs_num(fnum(a, 'range', 3.0)), cs_num(fnum(a, 'speed', 3.0)), cs_num(fnum(a, 'reshadowrange', 0.5)))
    if name == 'GrenadeToss':
        stype = a.get('type', 'targeted').lower()
        eff = a.get('effect')
        named = {}
        cd = ms(fnum(a, 'cooldown', 1.0))
        if stype == 'auto':
            named['fixedAngle'] = cs_num(fnum(a, 'defaultangle', 90.0)) + 'f'
        named['cooldown'] = str(cd)
        if fbool(a, 'cooldownjitter', False):
            named['cooldownVariance'] = str(cd // 2)
        if eff:
            e = effect_enum(eff, oid)
            if e:
                named['effect'] = e
                named['effectDuration'] = str(ms(fnum(a, 'duration', 0.0)))
        if a.get('minrange'):
            REPORT.add('approximations', f'{oid}: GrenadeToss minRange ignored')
        return 'new Grenade({}f, {}, {}f, {})'.format(
            cs_num(fnum(a, 'range', 8.0)), inum(a, 'damage', 10), cs_num(fnum(a, 'radius', 1.0)),
            ', '.join(f'{k}: {v}' for k, v in named.items()))
    if name == 'ObjectToss':
        stype = a.get('type', 'targeted').lower()
        rng = fnum(a, 'range', 8.0)
        jit = fnum(a, 'rangejitter', 0.0)
        cd = ms(fnum(a, 'cooldown', 1.0))
        named = {}
        if stype == 'auto':
            named['angle'] = cs_num(fnum(a, 'defaultangle', 90.0))
        else:
            REPORT.add('approximations', f'{oid}: targeted ObjectToss of "{a.get("childid", oid)}" tossed at a random angle (TossObject has no player targeting)')
        named['cooldown'] = str(cd)
        if fbool(a, 'cooldownjitter', False):
            named['cooldownVariance'] = str(cd // 2)
        if jit:
            named['minRange'] = cs_num(max(0.0, rng - jit))
            named['maxRange'] = cs_num(rng + jit)
        return 'new TossObject({}, {}, {})'.format(cs_str(a.get('childid', oid)), cs_num(rng),
                                                  ', '.join(f'{k}: {v}' for k, v in named.items()))
    if name == 'Walk':
        return 'new Walk({}, speed: {})'.format(cs_str(a.get('groundtypes', '')), cs_num(fnum(a, 'speed', 0.4)))
    if name == 'ShowEffect':
        return 'new ShowEffect({}, color: 0x{:X}, flashPeriod: {}, flashRepeats: {})'.format(
            cs_str(a.get('type', 'Flash')), hexcolor(a, 'color', 0xFFFFFF),
            cs_num(fnum(a, 'flashperiod', 0.75)), inum(a, 'flashrepeats', 1))
    if name == 'ConditionEffect':
        effs = [e for e in re.split(r'\s*,\s*', a.get('effect', '')) if e]
        out = []
        dur = fnum(a, 'duration', 0.0)
        for e in effs:
            en = effect_enum(e, oid)
            if en:
                out.append(f'new ConditionalEffect({en})' if dur <= 0 else
                           f'new ConditionalEffect({en}, false, {ms(dur)})')
        if a.get('cooldown'):
            REPORT.add('approximations', f'{oid}: ConditionEffect cooldown ignored (applied once per state entry)')
        if not out:
            return None
        return out if len(out) > 1 else out[0]
    if name == 'SetAltTexture':
        return f'new SetAltTexture({inum(a, "alttextureid", 0)})'
    if name == 'SetTag':
        return f'new SetTag({cs_str(a.get("tagname", ""))})'
    if name == 'ClearTag':
        return f'new SetTag({cs_str(a.get("tagname", ""))}, set: false)'
    if name == 'SetGlobalTag':
        return 'new SetGlobalTag({}, sendNotification: {})'.format(cs_str(a.get('tagname', '')), cs_num(fbool(a, 'sendnotification', False)))
    if name == 'ClearGlobalTag':
        return f'new SetGlobalTag({cs_str(a.get("tagname", ""))}, set: false)'
    if name == 'RestoresBreath':
        return 'new RestoresBreath({}, {})'.format(cs_num(fnum(a, 'radius', 1.0)), cs_num(fnum(a, 'speed', 50.0)))
    if name == 'CopyDamageRecord':
        return 'new CopyDamageRecord({}, {})'.format(cs_str(a.get('targetid', '')), cs_num(fnum(a, 'range', 40.0)))
    if name == 'ChangeGround':
        return f'new GroundTransform({cs_str(a.get("groundid", ""))})'
    if name == 'PlaySound':
        return f'new PlaySound({inum(a, "soundid", 0)})'
    if name == 'PlaceMap':
        return 'new PlaceMap({}, maxPlace: {}, cooldown: {})'.format(cs_str(a.get('map', '')), inum(a, 'maxplace', 1), ms(fnum(a, 'cooldown', 5.0)))
    if name == 'DeleteObject':
        return 'new DeleteObject({}, {})'.format(cs_str(a.get('objectid', '')), cs_num(fnum(a, 'radius', 0.0)))
    if name == 'ConditionEffectAura':
        return 'new ConditionEffectAura({}, range: {}, cooldown: {}, duration: {})'.format(
            cs_str(a.get('effect', '')), cs_num(fnum(a, 'range', 0.0)), ms(fnum(a, 'cooldown', 1.0)),
            ms(fnum(a, 'duration', -1.0)) if fnum(a, 'duration', -1.0) > 0 else -1)
    if name == 'ClearConditionEffectAura':
        return 'new ConditionEffectAura({}, range: {}, cooldown: {}, remove: true, ignoreInvisible: {})'.format(
            cs_str(a.get('effect', '')), cs_num(fnum(a, 'range', 0.0)), ms(fnum(a, 'cooldown', 1.0)),
            cs_num(fbool(a, 'ignoreinvisible', True)))
    REPORT.add('skipped behaviors', f'{oid}: unknown behavior "{name}"')
    return None


